def slugify(name: str) -> str:
    s = re.sub(r"[^\w\u4e00-\u9fff]+", "-", name).strip("-").lower()
    return s

def detect_province(name: str) -> str:
    for k in sorted(CITY, key=len, reverse=True):
        if k in name:
            return CITY[k]
    for p in PROVINCE_SET:
        if p in name:
            return p
    return ""

def main():
    out = []
    for name, date, kind, cat in RACES:
        status = "finished" if date < NOW else "pending"
        race = {
            "id": slugify(name),
            "name": name,
            "country": "中国",
            "province": detect_province(name),
            "raceDate": date,
            "regStatus": status,
            "events": ["全程马拉松", "半程马拉松"] if kind == "full" else ["半程马拉松"],
            "category": cat,
            "updatedAt": UPDATED,
        }
        ov = OVERRIDES.get(name, {})
        race.update(ov)
        out.append(race)

    # 去重检查
    ids = [r["id"] for r in out]
    assert len(ids) == len(set(ids)), "存在重复 id"
    with open("data/races.json", "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)
    prov_count = sum(1 for r in out if r["province"])
    print(f"生成 {len(out)} 场国内赛事，其中 {prov_count} 场识别出省份")

